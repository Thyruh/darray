#include <stdint.h>
typedef int8_t i8;
typedef int16_t i16;
typedef int32_t i32;
typedef int64_t i64;
typedef uint8_t u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef uint64_t u64;

typedef bool b32;

typedef float f32;
typedef double f64;

#include "darray.h"


DARRAY_INIT(i32)
DARRAY_INIT(Darray_i32)

int main(void) {
   Darray_i32 m_i32s = i32_new();
   Darray_Darray_i32 m_v_i32s = Darray_i32_new();

   Darray_i32* i32s = &m_i32s;
   Darray_Darray_i32* v_i32s = &m_v_i32s;

   i32_reserve(i32s, 100);
   for (u32 i = 0; i < 100; i++) i32_push(i32s, i << 1);

   printf("-------------------------------------- Darray of darrays ----------------------------------\n");

   Darray_i32_push(v_i32s, *i32s);
   printf("%d\n", *i32_at(Darray_i32_at(v_i32s, 0), 2));

   printf("-------------------------------------- Full darray of integers ----------------------------------\n");

   printf("elements: ");
   for (u32 i = 0; i < i32s->size-1; i++) {
      printf("%d, ", *i32_at(i32s, i));
   }
   printf("%d.\n", *i32_at(i32s, i32s->size-1));
   printf("length = %zu\n", i32s->size);

   i32_pop(i32s, 10);

   printf("-------------------------------------- Popped darray of integers ----------------------------------\n");
   
   printf("POPPED 10 ELEMENTS\n");

   printf("elements: ");
   for (u32 i = 0; i < i32s->size-1; i++) {
      i32* element = i32_at(i32s, i);
      if (!element) { // NULL pointer
         fprintf(stderr, "[ERROR]: Out of bounds access at %s:%d:%s\n", __FILE__, __LINE__-2, " _at()");
         printf("!HERE!\n");
         exit(1);
      }
      printf("%d, ", *element);
   }
   printf("%d.\n", *i32_at(i32s, i32s->size-1));
   printf("length = %zu\n", i32s->size);

   printf("-------------------------------------- Unsafe access ----------------------------------\n");

   printf("elements: ");
   for (u32 i = 0; i < 120; i++) {
      printf("%d, ", *i32_unsafe_at(i32s, i));
   }
   printf("%d.\n", *i32_unsafe_at(i32s, 120));
   printf("length = %zu\n", i32s->size);

   i32_free(i32s);
   Darray_i32_free(v_i32s);

   return 0;
}


